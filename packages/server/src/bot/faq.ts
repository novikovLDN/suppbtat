/* ─── keyboards ─────────────────────────────────────────────── */

export function faqHomeKeyboard(): InlineKeyboard {
  const kb = new InlineKeyboard();
  FAQ.forEach((c, i) => {
    kb.text(`${c.emoji} ${c.title}`, `faq:c:${i}`).row();
  });
  kb.text('💬 Позвать оператора', 'faq:op');
  return kb;
}

export function faqCategoryKeyboard(ci: number): InlineKeyboard {
  const kb = new InlineKeyboard();
  FAQ[ci].questions.forEach((q, qi) => kb.text(q.q, `faq:q:${ci}:${qi}`).row());
  kb.text('↩️ Назад', 'faq:home').text('💬 Другой вопрос', `faq:o:${ci}`);
  return kb;
}

export function faqAnswerKeyboard(ci: number, qi: number): InlineKeyboard {
  return new InlineKeyboard()
    .text('↩️ Назад', `faq:c:${ci}`)
    .text('💬 Позвать оператора', `faq:o:${ci}:${qi}`);
}
